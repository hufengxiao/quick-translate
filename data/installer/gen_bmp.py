def draw_text(pixels, bw, bh, x, y, text, color, scale=1):
    cx = x
    for ch in text:
        glyph = FONT.get(ch)
        if not glyph:
            cx += 6 * scale
            continue
        for ci in range(5):
            byte = glyph[ci]
            for ri in range(7):
                if byte & (1 << ri):
                    for sy in range(scale):
                        for sx in range(scale):
                            px = cx + ci * scale + sx
                            py = y + ri * scale + sy
                            if 0 <= px < bw and 0 <= py < bh:
                                pixels[py * bw + px] = color
        cx += 6 * scale


