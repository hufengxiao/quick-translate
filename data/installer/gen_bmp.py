"""Generate installer BMP images — pure Python, no dependencies."""
import struct, os

def write_bmp(path, w, h, pixels):
    row_size = (w * 3 + 3) & ~3
    data_size = row_size * h
    with open(path, "wb") as f:
        f.write(b"BM")
        f.write(struct.pack("<I", 54 + data_size))
        f.write(struct.pack("<HH", 0, 0))
        f.write(struct.pack("<I", 54))
        f.write(struct.pack("<I", 40))
        f.write(struct.pack("<i", w))
        f.write(struct.pack("<i", h))
        f.write(struct.pack("<HH", 1, 24))
        f.write(struct.pack("<I", 0))
        f.write(struct.pack("<I", data_size))
        f.write(struct.pack("<ii", 0, 0))
        f.write(struct.pack("<II", 0, 0))
        for row in range(h - 1, -1, -1):
            for col in range(w):
                r, g, b = pixels[row * w + col]
                f.write(struct.pack("BBB", b, g, r))
            f.write(b"\x00" * (row_size - w * 3))

def lerp(c1, c2, t):
    return tuple(int(c1[i] + (c2[i] - c1[i]) * t) for i in range(3))

def draw_circle(pixels, w, h, cx, cy, r, color):
    for y in range(max(0, cy - r - 1), min(h, cy + r + 1)):
        for x in range(max(0, cx - r - 1), min(w, cx + r + 1)):
            if (x - cx) ** 2 + (y - cy) ** 2 <= r * r:
                pixels[y * w + x] = color

